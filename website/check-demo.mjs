import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
const root=path.join(path.dirname(fileURLToPath(import.meta.url)),'dist');
const home=fs.readFileSync(path.join(root,'index.html'),'utf8');
const html=fs.readFileSync(path.join(root,'demo/index.html'),'utf8');
assert.ok(home.includes('sandbox="allow-scripts"'));
assert.ok(!home.includes('allow-same-origin'));
assert.ok(html.includes("connect-src 'none'"));
assert.ok(html.includes('noindex,follow'));
assert.ok(home.includes('id="reset-demo"'));
const config=JSON.parse(fs.readFileSync(path.join(root,'edgeone.json')));
assert.ok(config.headers.find(rule=>rule.source==='/demo/*')?.headers.some(h=>h.key==='Access-Control-Allow-Origin'&&h.value==='*'));
const assets=[...html.matchAll(/(?:src|href)="(\/demo\/assets\/[^"?#]+)"/g)].map(m=>m[1]);
assert.ok(assets.length>=2);
for(const asset of assets)assert.ok(fs.existsSync(path.join(root,asset.slice(1))),asset);
const files=fs.readdirSync(path.join(root,'demo/assets')).filter(f=>f.endsWith('.js'));
const scripts=files.map(f=>fs.readFileSync(path.join(root,'demo/assets',f),'utf8')).join('\n');
assert.ok(scripts.includes('网页演示不会访问或修改你的电脑'));
assert.ok(!scripts.includes('__TAURI_INTERNALS__.invoke'));
assert.ok(!scripts.includes('ipc://localhost'));
console.log(JSON.stringify({sandbox:'scripts only; opaque origin',apiNetwork:'blocked by CSP',nativeTransport:'not bundled',entryAssets:assets.length,jsChunks:files.length}));
